#!/usr/bin/env python3
"""Codex が使えない環境で、B-roll のダミー画像を作る。

broll.json のシーン定義から、シーン番号とプロンプト冒頭を焼き込んだグラデーション画像を
生成する。gen_broll.py の出力と同じ場所・同じ命名なので、make_video.py の動作確認や
尺のあたりを取るのにそのまま使える。**本番の素材ではない。**

usage:
    python3 placeholder_broll.py broll.json [--size 1920x1080]

必要なもの: Pillow
"""

from __future__ import annotations

import argparse
import json
import math
import sys
from pathlib import Path

try:
    from PIL import Image, ImageDraw, ImageFilter, ImageFont
except ImportError:
    sys.exit("placeholder_broll.py: Pillow が必要です — pip install Pillow")

FONT_CANDIDATES = [
    "/usr/share/fonts/truetype/fonts-japanese-gothic.ttf",
    "/usr/share/fonts/opentype/ipafont-gothic/ipagp.ttf",
    "/System/Library/Fonts/ヒラギノ角ゴシック W6.ttc",
    "/Library/Fonts/Arial Unicode.ttf",
    "C:/Windows/Fonts/meiryo.ttc",
]

# 落ち着いた寒色系。B-roll らしく見えるよう彩度は抑えめにする。
PALETTES = [
    ((18, 24, 38), (52, 88, 120)),
    ((22, 30, 34), (86, 110, 108)),
    ((28, 22, 40), (94, 74, 122)),
    ((16, 28, 32), (60, 104, 116)),
    ((34, 26, 24), (128, 92, 68)),
]


def load_font(size: int):
    for path in FONT_CANDIDATES:
        if Path(path).exists():
            try:
                return ImageFont.truetype(path, size)
            except OSError:
                continue
    return ImageFont.load_default()


def gradient(size: tuple[int, int], top: tuple, bottom: tuple, seed: int) -> Image.Image:
    width, height = size
    img = Image.new("RGB", size)
    draw = ImageDraw.Draw(img)
    for y in range(height):
        t = y / max(height - 1, 1)
        # 直線グラデだと平板なので、わずかに波打たせて奥行きを出す
        t = min(max(t + 0.06 * math.sin(t * math.pi * 2 + seed), 0.0), 1.0)
        draw.line(
            [(0, y), (width, y)],
            fill=tuple(int(top[i] + (bottom[i] - top[i]) * t) for i in range(3)),
        )

    # ぼかした光源をいくつか置いて、のっぺり感を消す
    glow = Image.new("RGB", size, (0, 0, 0))
    gdraw = ImageDraw.Draw(glow)
    for i in range(3):
        cx = int(width * (0.2 + 0.3 * ((seed + i * 3) % 3)))
        cy = int(height * (0.25 + 0.2 * ((seed + i) % 3)))
        r = int(min(width, height) * (0.18 + 0.06 * (i % 3)))
        gdraw.ellipse([cx - r, cy - r, cx + r, cy + r], fill=(70, 80, 95))
    glow = glow.filter(ImageFilter.GaussianBlur(radius=min(width, height) // 8))
    return Image.blend(img, Image.blend(img, glow, 0.35), 0.8)


def wrap(text: str, font, draw, max_width: int, max_lines: int) -> list[str]:
    lines: list[str] = []
    current = ""
    for char in text:
        if draw.textlength(current + char, font=font) > max_width:
            lines.append(current)
            current = char
            if len(lines) == max_lines:
                return lines[:-1] + [lines[-1][:-1] + "…"]
        else:
            current += char
    if current:
        lines.append(current)
    return lines


def render(scene: dict, index: int, size: tuple[int, int], out: Path) -> None:
    width, height = size
    top, bottom = PALETTES[index % len(PALETTES)]
    img = gradient(size, top, bottom, seed=index)
    draw = ImageDraw.Draw(img, "RGBA")

    scale = width / 1920

    # 下半分を緩やかに落としてテロップが乗る余白を作る（本番の style 指定と同じ意図）。
    # 直線的な矩形で塗ると境目が線として見えるので、下に向かって濃くする。
    fade_top = int(height * 0.45)
    for y in range(fade_top, height):
        t = (y - fade_top) / max(height - fade_top - 1, 1)
        draw.line([(0, y), (width, y)], fill=(0, 0, 0, int(110 * t)))

    # 焼き込む情報はすべて画面上部に寄せる。中央〜下はテロップの領域なので空けておく。
    tag_font = load_font(int(30 * scale))
    draw.text(
        (int(60 * scale), int(46 * scale)),
        "PLACEHOLDER — not generated by gpt-image-2",
        font=tag_font,
        fill=(255, 255, 255, 130),
    )

    label_font = load_font(int(120 * scale))
    label = scene["id"].upper()
    lw = draw.textlength(label, font=label_font)
    draw.text(((width - lw) / 2, int(110 * scale)), label, font=label_font, fill=(255, 255, 255, 65))

    body_font = load_font(int(34 * scale))
    y = int(275 * scale)
    for line in wrap(scene.get("prompt", ""), body_font, draw, int(width * 0.68), 3):
        lw = draw.textlength(line, font=body_font)
        draw.text(((width - lw) / 2, y), line, font=body_font, fill=(255, 255, 255, 165))
        y += int(48 * scale)

    out.parent.mkdir(parents=True, exist_ok=True)
    img.save(out)


def main() -> int:
    parser = argparse.ArgumentParser(description="B-roll のダミー画像を作る")
    parser.add_argument("config", type=Path, help="broll.json")
    parser.add_argument("--size", default="1920x1080", help="出力サイズ (default: 1920x1080)")
    args = parser.parse_args()

    try:
        config = json.loads(args.config.read_text(encoding="utf-8"))
    except FileNotFoundError:
        sys.exit(f"placeholder_broll.py: 設定ファイルがありません: {args.config}")

    scenes = config.get("scenes") or []
    if not scenes:
        sys.exit("placeholder_broll.py: `scenes` が空です")

    try:
        width, height = (int(v) for v in args.size.split("x"))
    except ValueError:
        sys.exit(f"placeholder_broll.py: --size の形式が不正です: {args.size}")

    out_dir = Path(config.get("output_dir", "broll"))
    if not out_dir.is_absolute():
        out_dir = (args.config.resolve().parent / out_dir).resolve()

    for index, scene in enumerate(scenes):
        scene_id = str(scene.get("id") or f"s{index + 1:02d}")
        out = out_dir / f"{scene_id}.png"
        render({**scene, "id": scene_id}, index, (width, height), out)
        print(f"[placeholder] {out}")

    print(f"\n{len(scenes)} 枚。本番は gen_broll.py で置き換えてください。")
    return 0


if __name__ == "__main__":
    sys.exit(main())
